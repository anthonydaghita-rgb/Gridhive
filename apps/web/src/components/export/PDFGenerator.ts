function buildNetworkOverview(ctx: ReportContext) {
  const { topology, validationResults, lastValidatedAt } = ctx

  const vlans = [...new Set(topology.nodes.flatMap(n => {
    const vlans = []
    if (n.data.vlanId) vlans.push(`VLAN ${n.data.vlanId}`)
    return vlans
  }))].join(', ') || 'None defined'

  const subnets = [...new Set(topology.nodes
    .filter(n => n.data.subnet)
    .map(n => n.data.subnet!))].join(', ') || 'None defined'

  const protocols = [...new Set(topology.edges.flatMap(e => {
    const p = e.data.protocols || []
    return p.map(proto => PROTOCOL_LABELS[proto] || proto)
  }))].join(', ') || 'None'

  const errors = validationResults.filter(r => r.severity === 'error').length
  const warnings = validationResults.filter(r => r.severity === 'warning').length
  const validationStatus = lastValidatedAt
    ? errors > 0 ? `ERRORS (${errors} errors, ${warnings} warnings)`
    : warnings > 0 ? `WARNINGS (${warnings} warnings)`
    : 'CLEAN'
    : 'Not run'

  const content: object[] = [
    { text: 'Network Overview', style: 'sectionHeader', pageBreak: 'before' },
  ]

  if (ctx.canvasImageBase64) {
    content.push({
      image: ctx.canvasImageBase64,
      width: 515,
      margin: [0, 0, 0, 16],
    })
  }

  content.push({
    table: {
      widths: [150, '*'],
      body: [
        [{ text: 'Total Devices', style: 'tableHeader' }, { text: topology.nodes.length.toString(), style: 'tableCell' }],
        [{ text: 'Total Connections', style: 'tableHeader' }, { text: topology.edges.length.toString(), style: 'tableCell' }],
        [{ text: 'VLANs Defined', style: 'tableHeader' }, { text: vlans, style: 'tableCell' }],
        [{ text: 'Subnets in Use', style: 'tableHeader' }, { text: subnets, style: 'tableCell' }],
        [{ text: 'Protocols in Use', style: 'tableHeader' }, { text: protocols, style: 'tableCell' }],
        [{ text: 'Validation Status', style: 'tableHeader' }, {
          text: validationStatus,
          style: 'tableCell',
          color: errors > 0 ? COLORS.errorRed : warnings > 0 ? COLORS.warningAmber : COLORS.successGreen,
        }],
        [{ text: 'Last Validated', style: 'tableHeader' }, { text: formatDate(lastValidatedAt), style: 'tableCell' }],
      ],
    },
    layout: {
      hLineWidth: () => 0.5,
      vLineWidth: () => 0,
      hLineColor: () => COLORS.border,
      fillColor: (i: number) => i % 2 === 0 ? COLORS.rowAlt : null,
    },
  })

  return content
}

function buildDeviceInventory(ctx: ReportContext, validationResults: ValidationResult[]) {
  const errorNodeIds = new Set(validationResults.filter(r => r.severity === 'error').flatMap(r => r.affectedNodeIds))
  const warningNodeIds = new Set(validationResults.filter(r => r.severity === 'warning').flatMap(r => r.affectedNodeIds))

  const headers = ['Hostname', 'Type', 'IP Address', 'Subnet', 'VLAN', 'Gateway', 'Role', 'Notes']
  const rows = ctx.topology.nodes.map(node => {
    const isError = errorNodeIds.has(node.id)
    const isWarning = warningNodeIds.has(node.id)
    const fill = isError ? COLORS.rowError : isWarning ? COLORS.rowWarning : null

    return headers.map((_, i) => {
      const values = [
        node.data.hostname || '',
        node.data.deviceType,
        node.data.ipAddress || '',
        node.data.subnet || '',
        node.data.vlanId?.toString() || '',
        node.data.defaultGateway || '',
        node.data.role || '',
        node.data.notes || '',
      ]
      return {
        text: values[i],
        style: 'tableCell',
        fillColor: fill,
      }
    })
  })

  return [
    { text: 'Device Inventory', style: 'sectionHeader', pageBreak: 'before' },
    {
      table: {
        headerRows: 1,
        widths: [80, 65, 75, 75, 35, 70, 50, '*'],
        body: [
          headers.map(h => ({ text: h, style: 'columnHeader' })),
          ...rows,
        ],
      },
      layout: {
        hLineWidth: () => 0.5,
        vLineWidth: (i: number) => i === 0 || i === headers.length ? 0.5 : 0,
        hLineColor: () => COLORS.border,
        vLineColor: () => COLORS.border,
        fillColor: (row: number) => row === 0 ? COLORS.headerBg : null,
      },
    },
  ]
}

function buildConnectionInventory(ctx: ReportContext) {
  const headers = ['Source', 'Destination', 'Connection Type', 'Speed', 'VLAN/Trunk', 'Notes']
  const rows = ctx.topology.edges.map(edge => {
    const source = ctx.topology.nodes.find(n => n.id === edge.source)
    const target = ctx.topology.nodes.find(n => n.id === edge.target)
    const connType = (edge.data as Record<string, unknown>).connectionType as string | undefined
    const vlanInfo = edge.data.vlanTag
      ? `VLAN ${edge.data.vlanTag}`
      : edge.data.trunkVlans?.length
      ? `Trunk: ${(edge.data.trunkVlans as number[]).join(', ')}`
      : ''

    return [
      { text: source?.data.hostname || edge.source, style: 'tableCell' },
      { text: target?.data.hostname || edge.target, style: 'tableCell' },
      { text: connType || edge.data.mediaType || 'ethernet-copper', style: 'tableCell' },
      { text: (edge.data as Record<string, unknown>).speed as string || '1G', style: 'tableCell' },
      { text: vlanInfo, style: 'tableCell' },
      { text: edge.data.notes || '', style: 'tableCell' },
    ]
  })

  return [
    { text: 'Connection Inventory', style: 'sectionHeader', pageBreak: 'before' },
    {
      table: {
        headerRows: 1,
        widths: [80, 80, 100, 40, 65, '*'],
        body: [
          headers.map(h => ({ text: h, style: 'columnHeader' })),
          ...rows,
        ],
      },
      layout: {
        hLineWidth: () => 0.5,
        vLineWidth: (i: number) => i === 0 || i === headers.length ? 0.5 : 0,
        hLineColor: () => COLORS.border,
        vLineColor: () => COLORS.border,
        fillColor: (row: number) => row === 0 ? COLORS.headerBg : row % 2 === 0 ? COLORS.rowAlt : null,
      },
    },
  ]
}

function buildLateralMovementSection(ctx: ReportContext) {
  const lm = ctx.lmResult
  const content: object[] = [
    { text: 'Lateral Movement Risk Analysis', style: 'sectionHeader', pageBreak: 'before' },
  ]

  if (!lm) {
    content.push({ text: 'No lateral movement simulation has been run. Open the Lateral Movement tab and run a simulation before exporting.', style: 'bodyText', margin: [0, 8] })
    return content
  }

  content.push({
    table: {
      widths: [150, '*'],
      body: [
        [{ text: 'Source Node', style: 'tableHeader' }, { text: ctx.topology.nodes.find(n => n.id === lm.sourceNodeId)?.data?.label as string || lm.sourceNodeId, style: 'tableCell' }],
        [{ text: 'Blast Radius Score', style: 'tableHeader' }, { text: `${lm.blastRadiusScore} / 100`, style: 'tableCell', bold: true }],
        [{ text: 'LMS Network Score', style: 'tableHeader' }, { text: `${lm.lmsScore} / 100`, style: 'tableCell' }],
        [{ text: 'Reachable Devices', style: 'tableHeader' }, { text: lm.reachability.filter(r => r.tier !== 'unreachable').length.toString(), style: 'tableCell' }],
        [{ text: 'Critical Assets at Risk', style: 'tableHeader' }, { text: lm.criticalAssetsAtRisk.length.toString(), style: 'tableCell', color: lm.criticalAssetsAtRisk.length > 0 ? COLORS.errorRed : COLORS.bodyText }],
      ],
    },
    layout: { hLineWidth: () => 0.5, vLineWidth: () => 0, hLineColor: () => COLORS.border, fillColor: (i: number) => i % 2 === 0 ? COLORS.rowAlt : null },
    margin: [0, 0, 0, 12],
  })

  const reached = lm.reachability.filter(r => r.tier !== 'unreachable').sort((a, b) => b.probability - a.probability)
  if (reached.length > 0) {
    content.push({ text: 'Reachable Devices', style: 'subSectionHeader', margin: [0, 8, 0, 4] })
    content.push({
      table: {
        headerRows: 1,
        widths: [140, 60, 40, '*'],
        body: [
          [{ text: 'Device', style: 'columnHeader' }, { text: 'Tier', style: 'columnHeader' }, { text: 'Hops', style: 'columnHeader' }, { text: 'Probability', style: 'columnHeader' }],
          ...reached.slice(0, 20).map(r => {
            const node = ctx.topology.nodes.find(n => n.id === r.nodeId)
            const tierColor = r.tier === 'primary' ? COLORS.errorRed : r.tier === 'secondary' ? COLORS.warningAmber : COLORS.infoBlue
            return [
              { text: node?.data?.label as string || r.nodeId, style: 'tableCell' },
              { text: r.tier.toUpperCase(), style: 'tableCell', color: tierColor, bold: true },
              { text: r.hops.toString(), style: 'tableCell' },
              { text: `${Math.round(r.probability * 100)}%`, style: 'tableCell' },
            ]
          }),
        ],
      },
      layout: { hLineWidth: () => 0.5, vLineWidth: (i: number) => i === 0 || i === 4 ? 0.5 : 0, hLineColor: () => COLORS.border, vLineColor: () => COLORS.border, fillColor: (row: number) => row === 0 ? COLORS.headerBg : row % 2 === 0 ? COLORS.rowAlt : null },
    })
  }

  if (lm.remediations.length > 0) {
    content.push({ text: 'Recommended Remediations', style: 'subSectionHeader', margin: [0, 12, 0, 4] })
    for (const rem of lm.remediations) {
      content.push({
        table: {
          widths: ['*'],
          body: [[{
            stack: [
              { text: `#${rem.rank} — Remediation`, bold: true, fontSize: 9, color: COLORS.primary },
              { text: rem.description, fontSize: 8, color: COLORS.bodyText, margin: [0, 2, 0, 0] },
              { text: `Blast radius reduction: ${rem.blastRadiusPctReduction}%`, fontSize: 8, color: COLORS.subtext, margin: [0, 2, 0, 0] },
            ],
            margin: [6, 4],
          }]],
        },
        layout: { hLineWidth: (i: number) => i === 0 || i === 1 ? 0.5 : 0, vLineWidth: (i: number) => i === 0 || i === 1 ? 0.5 : 0, hLineColor: () => COLORS.border, vLineColor: () => COLORS.border },
        margin: [0, 2],
      })
    }
  }

  return content
}

function buildCapacitySection(ctx: ReportContext) {
  const cap = ctx.capacityResult
  const content: object[] = [
    { text: 'Capacity Planning Analysis', style: 'sectionHeader', pageBreak: 'before' },
  ]

  if (!cap) {
    content.push({ text: 'No capacity analysis has been run. Open the Capacity tab and run an analysis before exporting.', style: 'bodyText', margin: [0, 8] })
    return content
  }

  content.push({
    table: {
      widths: [150, '*'],
      body: [
        [{ text: 'Total Avg Bandwidth', style: 'tableHeader' }, { text: formatMbps(cap.totalBandwidthAvgMbps), style: 'tableCell' }],
        [{ text: 'Total Peak Bandwidth', style: 'tableHeader' }, { text: formatMbps(cap.totalBandwidthPeakMbps), style: 'tableCell' }],
        [{ text: 'Overloaded Links', style: 'tableHeader' }, { text: cap.overloadedEdgeIds.length.toString(), style: 'tableCell', color: cap.overloadedEdgeIds.length > 0 ? COLORS.errorRed : COLORS.bodyText }],
        [{ text: 'At-Risk Links', style: 'tableHeader' }, { text: cap.atRiskEdgeIds.length.toString(), style: 'tableCell', color: cap.atRiskEdgeIds.length > 0 ? COLORS.warningAmber : COLORS.bodyText }],
      ],
    },
    layout: { hLineWidth: () => 0.5, vLineWidth: () => 0, hLineColor: () => COLORS.border, fillColor: (i: number) => i % 2 === 0 ? COLORS.rowAlt : null },
    margin: [0, 0, 0, 12],
  })

  const nonOk = cap.linkUtilization.filter(l => l.status !== 'ok').sort((a, b) => b.peakUtilizationPct - a.peakUtilizationPct)
  if (nonOk.length > 0) {
    content.push({ text: 'Link Utilization Issues', style: 'subSectionHeader', margin: [0, 8, 0, 4] })
    content.push({
      table: {
        headerRows: 1,
        widths: [130, 130, 50, 50, 50, 60],
        body: [
          [{ text: 'Source', style: 'columnHeader' }, { text: 'Destination', style: 'columnHeader' }, { text: 'Speed', style: 'columnHeader' }, { text: 'Avg %', style: 'columnHeader' }, { text: 'Peak %', style: 'columnHeader' }, { text: 'Status', style: 'columnHeader' }],
          ...nonOk.slice(0, 15).map(l => {
            const src = ctx.topology.nodes.find(n => n.id === l.sourceNodeId)
            const tgt = ctx.topology.nodes.find(n => n.id === l.targetNodeId)
            const stColor = l.status === 'critical' ? COLORS.errorRed : l.status === 'warning' ? COLORS.warningAmber : '#ca8a04'
            return [
              { text: src?.data?.label as string || l.sourceNodeId, style: 'tableCell' },
              { text: tgt?.data?.label as string || l.targetNodeId, style: 'tableCell' },
              { text: formatMbps(l.linkSpeedMbps), style: 'tableCell' },
              { text: `${l.avgUtilizationPct}%`, style: 'tableCell' },
              { text: `${l.peakUtilizationPct}%`, style: 'tableCell', bold: true, color: stColor },
              { text: l.status.toUpperCase(), style: 'tableCell', color: stColor, bold: true },
            ]
          }),
        ],
      },
      layout: { hLineWidth: () => 0.5, vLineWidth: (i: number) => i === 0 || i === 6 ? 0.5 : 0, hLineColor: () => COLORS.border, vLineColor: () => COLORS.border, fillColor: (row: number) => row === 0 ? COLORS.headerBg : row % 2 === 0 ? COLORS.rowAlt : null },
    })
  }

  if (cap.bottlenecks.length > 0) {
    content.push({ text: 'Bottleneck Recommendations', style: 'subSectionHeader', margin: [0, 12, 0, 4] })
    for (const b of cap.bottlenecks) {
      content.push({
        table: { widths: ['*'], body: [[{ stack: [{ text: b.description, bold: true, fontSize: 9, color: COLORS.warningAmber }, { text: b.recommendation, fontSize: 8, color: COLORS.bodyText, margin: [0, 2, 0, 0] }], margin: [6, 4] }]] },
        layout: { hLineWidth: (i: number) => i === 0 || i === 1 ? 0.5 : 0, vLineWidth: (i: number) => i === 0 || i === 1 ? 0.5 : 0, hLineColor: () => COLORS.border, vLineColor: () => COLORS.border },
        margin: [0, 2],
      })
    }
  }

  return content
}

function formatMbps(mbps: number): string {
  return mbps >= 1000 ? `${(mbps / 1000).toFixed(1)} Gbps` : `${mbps.toFixed(0)} Mbps`
}

function buildProtocolReference(ctx: ReportContext) {
  const allProtocols = [...new Set(ctx.topology.edges.flatMap(e => e.data.protocols || []))]

  if (allProtocols.length === 0) {
    return [
      { text: 'Protocols and Services', style: 'sectionHeader', pageBreak: 'before' },
      { text: 'No protocols assigned to any connection in this topology.', style: 'bodyText', margin: [0, 8] },
    ]
  }

  const rows = allProtocols.map(protocol => {
    const usedOn = ctx.topology.edges
      .filter(e => (e.data.protocols || []).includes(protocol))
      .map(e => {
        const src = ctx.topology.nodes.find(n => n.id === e.source)
        const tgt = ctx.topology.nodes.find(n => n.id === e.target)
        return `${src?.data.hostname || 'Unknown'} → ${tgt?.data.hostname || 'Unknown'}`
      }).join(', ')

    return [
      { text: PROTOCOL_LABELS[protocol] || protocol, style: 'tableCell', bold: true },
      { text: usedOn, style: 'tableCell' },
      { text: PROTOCOL_DESCRIPTIONS[protocol] || '', style: 'tableCell' },
    ]
  })

  return [
    { text: 'Protocols and Services', style: 'sectionHeader', pageBreak: 'before' },
    {
      table: {
        headerRows: 1,
        widths: [80, 160, '*'],
        body: [
          [
            { text: 'Protocol', style: 'columnHeader' },
            { text: 'Used On', style: 'columnHeader' },
            { text: 'Description', style: 'columnHeader' },
          ],
          ...rows,
        ],
      },
      layout: {
        hLineWidth: () => 0.5,
        vLineWidth: (i: number) => i === 0 || i === 3 ? 0.5 : 0,
        hLineColor: () => COLORS.border,
        vLineColor: () => COLORS.border,
        fillColor: (row: number) => row === 0 ? COLORS.headerBg : row % 2 === 0 ? COLORS.rowAlt : null,
      },
    },
  ]
}

function buildValidationReport(ctx: ReportContext) {
  const { validationResults, lastValidatedAt } = ctx

  const content: object[] = [
    { text: 'Validation Results', style: 'sectionHeader', pageBreak: 'before' },
  ]

  if (!lastValidatedAt) {
    content.push({
      text: 'Validation not run. Load the project and run Validate before exporting for a complete report.',
      style: 'bodyText',
      margin: [0, 8],
    })
    return content
  }

  if (validationResults.length === 0) {
    content.push({
      text: `Validation passed with no errors or warnings at ${formatDate(lastValidatedAt)}.`,
      style: 'bodyText',
      color: COLORS.successGreen,
      margin: [0, 8],
    })
    return content
  }

  for (const severity of ['error', 'warning', 'info'] as const) {
    const items = validationResults.filter(r => r.severity === severity)
    if (items.length === 0) continue

    const sectionColor = severity === 'error' ? COLORS.errorRed : severity === 'warning' ? COLORS.warningAmber : COLORS.infoBlue
    const label = severity === 'error' ? 'Errors' : severity === 'warning' ? 'Warnings' : 'Info'

    content.push({ text: `${label} (${items.length})`, style: 'subSectionHeader', color: sectionColor, margin: [0, 12, 0, 4] })

    for (const result of items) {
      content.push({
        table: {
          widths: ['*'],
          body: [[{
            stack: [
              { text: `${result.code}: ${result.title}`, bold: true, fontSize: 9, color: sectionColor },
              { text: result.description, fontSize: 8, color: COLORS.bodyText, margin: [0, 2, 0, 0] },
              result.recommendation
                ? { text: `Recommendation: ${result.recommendation}`, fontSize: 8, color: COLORS.subtext, margin: [0, 2, 0, 0], italics: true }
                : { text: '' },
            ],
            margin: [6, 4],
          }]],
        },
        layout: {
          hLineWidth: (i: number) => i === 0 || i === 1 ? 0.5 : 0,
          vLineWidth: (i: number) => i === 0 || i === 1 ? 0.5 : 0,
          hLineColor: () => sectionColor,
          vLineColor: () => sectionColor,
        },
        margin: [0, 2, 0, 2],
      })
    }
  }

  return content
}

function buildSimulationReport(ctx: ReportContext) {
  const { simulationResults, simulationTests, lastSimulatedAt } = ctx

  const content: object[] = [
    { text: 'Simulation Test Results', style: 'sectionHeader', pageBreak: 'before' },
  ]

  if (!lastSimulatedAt || simulationResults.length === 0) {
    content.push({
      text: 'Simulation tests have not been run for this topology.',
      style: 'bodyText',
      margin: [0, 8],
    })
    return content
  }

  for (const result of simulationResults) {
    const test = simulationTests.find(t => t.id === result.testId)
    const testName = test?.name || result.testId
    const resultColor = result.passed ? COLORS.successGreen : COLORS.errorRed

    content.push({
      table: {
        widths: ['*'],
        body: [[{
          stack: [
            {
              columns: [
                { text: testName, bold: true, fontSize: 9, width: '*' },
                { text: result.passed ? 'PASS' : 'FAIL', color: resultColor, bold: true, fontSize: 9, width: 'auto' },
              ],
            },
            test?.type ? { text: `Type: ${test.type}`, fontSize: 8, color: COLORS.subtext, margin: [0, 2, 0, 0] } : { text: '' },
            result.path.length > 0
              ? {
                  text: `Path: ${result.path.map(h => h.nodeLabel).join(' → ')}`,
                  fontSize: 8,
                  color: COLORS.bodyText,
                  margin: [0, 3, 0, 0],
                }
              : { text: '' },
            result.blockReason
              ? {
                  text: `Blocked: ${result.blockReason}`,
                  fontSize: 8,
                  color: COLORS.errorRed,
                  margin: [0, 2, 0, 0],
                }
              : { text: '' },
          ],
          margin: [6, 4],
        }]],
      },
      layout: {
        hLineWidth: (i: number) => i === 0 || i === 1 ? 0.5 : 0,
        vLineWidth: (i: number) => i === 0 || i === 1 ? 0.5 : 0,
        hLineColor: () => resultColor,
        vLineColor: () => resultColor,
      },
      margin: [0, 2, 0, 4],
    })
  }

  return content
}

function buildSubnetReference(ctx: ReportContext) {
  const nodesBySubnet: Record<string, typeof ctx.topology.nodes> = {}

  for (const node of ctx.topology.nodes) {
    if (node.data.subnet) {
      if (!nodesBySubnet[node.data.subnet]) nodesBySubnet[node.data.subnet] = []
      nodesBySubnet[node.data.subnet].push(node)
    }
  }

  const content: object[] = [
    { text: 'IP Addressing Reference', style: 'sectionHeader', pageBreak: 'before' },
  ]

  if (Object.keys(nodesBySubnet).length === 0) {
    content.push({ text: 'No subnets defined in this topology.', style: 'bodyText', margin: [0, 8] })
    return content
  }

  for (const [subnet, nodes] of Object.entries(nodesBySubnet)) {
    const assigned = nodes.map(n => `${n.data.ipAddress || 'unassigned'} → ${n.data.hostname}`).join(', ')
    content.push({
      table: {
        widths: [120, '*'],
        body: [
          [{ text: 'Subnet', style: 'tableHeader' }, { text: subnet, style: 'tableCell', bold: true }],
          [{ text: 'Assigned Devices', style: 'tableHeader' }, { text: assigned, style: 'tableCell' }],
        ],
      },
      layout: {
        hLineWidth: () => 0.5,
        vLineWidth: () => 0,
        hLineColor: () => COLORS.border,
        fillColor: (i: number) => i % 2 === 0 ? COLORS.rowAlt : null,
      },
      margin: [0, 4, 0, 8],
    })
  }

  return content
}

export async function generatePDF(ctx: ReportContext, options: PDFOptions): Promise<void> {
  // Dynamic import to keep bundle lean
  const pdfmake = await import('pdfmake/build/pdfmake')
  const pdfFonts = await import('pdfmake/build/vfs_fonts')

  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const pdfMakeLib = (pdfmake.default || pdfmake) as any
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const vfsFonts = pdfFonts as any
  const vfsData = vfsFonts?.default?.pdfMake?.vfs || vfsFonts?.pdfMake?.vfs
  if (vfsData) {
    pdfMakeLib.vfs = vfsData
  }
  const pdfMake = pdfMakeLib

  const content: object[] = [
    ...buildCoverPage(ctx),
    ...buildNetworkOverview(ctx),
    ...buildDeviceInventory(ctx, options.includeValidation ? ctx.validationResults : []),
    ...buildConnectionInventory(ctx),
    ...buildProtocolReference(ctx),
  ]

  if (options.includeSubnet) {
    content.push(...buildSubnetReference(ctx))
  }

  if (options.includeValidation) {
    content.push(...buildValidationReport(ctx))
  }

  if (options.includeSimulation) {
    content.push(...buildSimulationReport(ctx))
  }

  if (options.includeLateralMovement) {
    content.push(...buildLateralMovementSection(ctx))
  }

  if (options.includeCapacity) {
    content.push(...buildCapacitySection(ctx))
  }

  const pageSize = options.paperSize === 'A4' ? 'A4' : 'LETTER'

  const docDefinition = {
    pageSize,
    pageMargins: [40, 60, 40, 50] as [number, number, number, number],
    content,
    styles: {
      logo: {
        fontSize: 22,
        bold: true,
        color: COLORS.primary,
        letterSpacing: 3,
      },
      coverTitle: {
        fontSize: 28,
        bold: true,
        color: COLORS.headerBg,
        margin: [0, 20, 0, 8],
      },
      coverSubtitle: {
        fontSize: 14,
        color: COLORS.subtext,
        margin: [0, 0, 0, 30],
      },
      metaLabel: {
        fontSize: 9,
        color: COLORS.subtext,
        bold: true,
        margin: [0, 4, 0, 4],
      },
      metaValue: {
        fontSize: 9,
        color: COLORS.bodyText,
        margin: [0, 4, 0, 4],
      },
      sectionHeader: {
        fontSize: 16,
        bold: true,
        color: COLORS.primary,
        margin: [0, 0, 0, 16],
      },
      subSectionHeader: {
        fontSize: 12,
        bold: true,
        margin: [0, 8, 0, 4],
      },
      columnHeader: {
        fontSize: 8,
        bold: true,
        color: COLORS.headerText,
        fillColor: COLORS.headerBg,
        margin: [4, 4, 4, 4],
      },
      tableHeader: {
        fontSize: 8,
        bold: true,
        color: COLORS.subtext,
        margin: [4, 4, 4, 4],
      },
      tableCell: {
        fontSize: 8,
        color: COLORS.bodyText,
        margin: [4, 3, 4, 3],
      },
      bodyText: {
        fontSize: 9,
        color: COLORS.bodyText,
        lineHeight: 1.4,
      },
    },
    footer: (currentPage: number, pageCount: number) => ({
      columns: [
        { text: `Gridhive | ${ctx.orgName}`, fontSize: 8, color: '#64748b', alignment: 'left' },
        { text: ctx.projectName, fontSize: 8, color: '#64748b', alignment: 'center' },
        { text: `Page ${currentPage} of ${pageCount}`, fontSize: 8, color: '#64748b', alignment: 'right' },
      ],
      margin: [40, 10, 40, 0] as [number, number, number, number],
    }),
    defaultStyle: {
      font: 'Roboto',
      fontSize: 9,
    },
  }

  const now = new Date()
  const dateStr = `${now.getFullYear()}${String(now.getMonth() + 1).padStart(2, '0')}${String(now.getDate()).padStart(2, '0')}`
  const filename = `${ctx.projectName.replace(/[^a-zA-Z0-9]/g, '_')}_${dateStr}_Network_Report.pdf`

  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  pdfMake.createPdf(docDefinition as any).download(filename)
}
